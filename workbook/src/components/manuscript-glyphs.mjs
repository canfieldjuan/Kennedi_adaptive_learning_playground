export function glyphPaths(letter) {
  if (typeof letter !== 'string' || !Object.hasOwn(GLYPHS, letter)) {
    throw new TypeError(`Expected one A-Z or a-z letter; received ${JSON.stringify(letter)}`);
  }
  return GLYPHS[letter];
}
